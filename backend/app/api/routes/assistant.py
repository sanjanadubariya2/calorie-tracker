# ============================================================================ API schemas

class SummaryOut(BaseModel):
    summary: str
    key_facts: list[str]
    open_questions: list[str]


class ConversationOut(BaseModel):
    id: uuid.UUID
    title: str | None
    message_count: int
    created_at: dt.datetime
    updated_at: dt.datetime
    expires_at: dt.datetime
    summary: SummaryOut | None
    summary_updated_at: dt.datetime | None

    @classmethod
    def of(cls, c: Conversation) -> "ConversationOut":
        summary = None
        if c.summary:
            try:
                summary = SummaryOut.model_validate(c.summary)
            except ValueError:
                summary = None
        return cls(id=c.id, title=c.title, message_count=c.message_count, created_at=c.created_at,
                   updated_at=c.updated_at, expires_at=c.expires_at, summary=summary,
                   summary_updated_at=c.summary_updated_at)


class MessageOut(BaseModel):
    id: uuid.UUID
    seq: int
    role: str
    content: str
    response: AssistantResponse | None = None
    outcome: str | None = None
    client_message_id: uuid.UUID | None = None
    created_at: dt.datetime

    @classmethod
    def of(cls, m: StoredMessage) -> "MessageOut":
        response = None
        if m.role == "assistant" and m.response:
            try:
                response = parse_stored_response(m.response)
            except ValueError:
                response = None   # an old shape: the text content is still shown
        return cls(id=m.id, seq=m.seq, role=m.role, content=m.content, response=response, outcome=m.outcome,
                   client_message_id=m.client_message_id, created_at=m.created_at)


class ConversationCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    title: str | None = Field(default=None, max_length=120)

    @field_validator("title")
    @classmethod
    def _t(cls, v: str | None) -> str | None:
        v = " ".join(v.split()) if v else None
        return v or None


class ConversationPage(BaseModel):
    items: list[ConversationOut]
    next_before: dt.datetime | None


class MessagePage(BaseModel):
    items: list[MessageOut]
    next_before_seq: int | None


class MessageCreate(BaseModel):
    model_config = ConfigDict(extra="forbid")
    content: str = Field(min_length=1, max_length=8000)
    client_message_id: uuid.UUID = Field(description="Generated by the app; retrying with the same id never duplicates.")
    local_date: dt.date | None = Field(default=None, description="The user's local date (YYYY-MM-DD).")

    @field_validator("content")
    @classmethod
    def _c(cls, v: str) -> str:
        v = v.strip()
        if not v:
            raise ValueError("Message is empty.")
        return v

    @field_validator("local_date")
    @classmethod
    def _d(cls, v: dt.date | None) -> dt.date | None:
        if v is None:
            return v
        utc = dt.datetime.now(dt.timezone.utc).date()
        if abs((v - utc).days) > 1:
            raise ValueError("local_date must be within a day of the current date.")
        return v


class TurnOut(BaseModel):
    conversation: ConversationOut
    user_message: MessageOut
    assistant_message: MessageOut


# ============================================================================ helpers

def _service(request: Request) -> AssistantService:
    return request.app.state.assistant


def _require_turns(svc: AssistantService) -> None:
    if not svc.llm.configured:
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail="The assistant isn't available right now.")


def _llm_error(exc: LLMError) -> HTTPException:
    if isinstance(exc, LLMNotConfigured):
        return HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail="The assistant isn't available right now.")
    if isinstance(exc, LLMRateLimited):
        return HTTPException(status.HTTP_429_TOO_MANY_REQUESTS, detail="The assistant is busy. Try again shortly.",
                             headers={"Retry-After": str(exc.retry_after)} if exc.retry_after else None)
    if isinstance(exc, LLMTimeout):
        return HTTPException(status.HTTP_504_GATEWAY_TIMEOUT, detail="The assistant took too long. Please try again.")
    if isinstance(exc, (LLMUnavailable, LLMInvalidOutput, LLMRequestRejected)):
        return HTTPException(status.HTTP_502_BAD_GATEWAY, detail="The assistant had a problem. Please try again.")
    return HTTPException(status.HTTP_502_BAD_GATEWAY, detail="The assistant had a problem. Please try again.")


async def _with_current_proposals(svc: AssistantService, user: AuthenticatedUser,
                                  messages: list[MessageOut]) -> list[MessageOut]:
    """Proposal cards show the proposal's CURRENT status (confirmed, expired...),
    not the status it had when the message was written."""
    cards = [m.response.action.proposal for m in messages
             if m.response is not None and getattr(m.response, "type", None) == "proposed_action"]
    if not cards:
        return messages
    current = await svc.proposals.store.statuses(user, [c.id for c in cards])
    for card in cards:
        row = current.get(str(card.id))
        if row is not None:
            card.status = effective_status(row)
            card.food_log_ids = [uuid.UUID(str(i)) for i in row.get("food_log_ids") or []]
    return messages


async def _conversation_or_404(svc: AssistantService, user: AuthenticatedUser, conversation_id: uuid.UUID) -> Conversation:
    conv = await svc.store.get_conversation(user, conversation_id)
    if conv is None:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Conversation not found")
    return conv


# ============================================================================ conversations

@router.post("/v1/assistant/conversations", response_model=ConversationOut, status_code=status.HTTP_201_CREATED,
             summary="Start a conversation")
async def create_conversation(body: ConversationCreate, request: Request,
                              user: AuthenticatedUser = Depends(get_current_user)) -> ConversationOut:
    svc = _service(request)
    try:
        return ConversationOut.of(await svc.store.create_conversation(user, body.title))
    except StoreNotConfigured:
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail="The assistant isn't available right now.") from None


@router.get("/v1/assistant/conversations", response_model=ConversationPage, summary="Your conversations, newest first")
async def list_conversations(request: Request, user: AuthenticatedUser = Depends(get_current_user),
                             limit: int = Query(20, ge=1, le=50),
                             before: dt.datetime | None = Query(None, description="next_before from the previous page")
                             ) -> ConversationPage:
    items = await _service(request).store.list_conversations(user, limit, before)
    return ConversationPage(items=[ConversationOut.of(c) for c in items],
                            next_before=items[-1].updated_at if len(items) == limit else None)


@router.get("/v1/assistant/conversations/{conversation_id}", response_model=ConversationOut)
async def get_conversation(conversation_id: uuid.UUID, request: Request,
                           user: AuthenticatedUser = Depends(get_current_user)) -> ConversationOut:
    return ConversationOut.of(await _conversation_or_404(_service(request), user, conversation_id))


@router.delete("/v1/assistant/conversations/{conversation_id}", status_code=status.HTTP_204_NO_CONTENT,
               summary="Delete a conversation and all its messages")
async def delete_conversation(conversation_id: uuid.UUID, request: Request,
                              user: AuthenticatedUser = Depends(get_current_user)) -> Response:
    if not await _service(request).store.delete_conversation(user, conversation_id):
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Conversation not found")
    return Response(status_code=status.HTTP_204_NO_CONTENT)


@router.get("/v1/assistant/conversations/{conversation_id}/messages", response_model=MessagePage,
            summary="Messages in order (seq ascending); page backwards with before_seq")
async def list_messages(conversation_id: uuid.UUID, request: Request,
                        user: AuthenticatedUser = Depends(get_current_user),
                        limit: int = Query(50, ge=1, le=100), before_seq: int | None = Query(None, ge=1)) -> MessagePage:
    svc = _service(request)
    await _conversation_or_404(svc, user, conversation_id)
    items = await svc.store.list_messages(user, conversation_id, before_seq, limit)
    return MessagePage(items=await _with_current_proposals(svc, user, [MessageOut.of(m) for m in items]),
                       next_before_seq=items[0].seq if len(items) == limit and items[0].seq > 1 else None)


@router.post("/v1/assistant/conversations/{conversation_id}/messages", response_model=TurnOut,
             summary="Send a message and get the assistant's reply",
             responses={404: {"description": "Conversation not found"}, 409: {"description": "A reply is already being generated"},
                        429: {"description": "Rate limit or daily limit"}, 502: {"description": "AI provider problem"},
                        503: {"description": "Assistant not configured"}, 504: {"description": "AI provider timed out"}})
async def send_message(conversation_id: uuid.UUID, body: MessageCreate, request: Request,
                       background: BackgroundTasks, user: AuthenticatedUser = Depends(get_current_user)) -> TurnOut:
    svc = _service(request)
    _require_turns(svc)
    if len(body.content) > svc.settings.assistant_max_message_chars:
        raise HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY,
                            detail=f"Keep messages under {svc.settings.assistant_max_message_chars} characters.")
    try:
        conv, user_msg, reply = await svc.send_message(user, conversation_id, body.content, body.client_message_id,
                                                       body.local_date)
    except ConversationNotFound:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Conversation not found") from None
    except TurnInProgress:
        raise HTTPException(status.HTTP_409_CONFLICT, detail="A reply is already being generated in this conversation.") from None
    except RateLimited as exc:
        raise HTTPException(status.HTTP_429_TOO_MANY_REQUESTS, detail=exc.message,
                            headers={"Retry-After": str(exc.retry_after)}) from None
    except StoreNotConfigured:
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail="The assistant isn't available right now.") from None
    except LLMError as exc:
        raise _llm_error(exc) from None
    background.add_task(svc.maybe_summarize, user, conversation_id)
    return TurnOut(conversation=ConversationOut.of(conv), user_message=MessageOut.of(user_msg),
                   assistant_message=MessageOut.of(reply))


@router.post("/v1/assistant/conversations/{conversation_id}/summary", response_model=ConversationOut,
             summary="Regenerate this conversation's summary from scratch")
async def regenerate_summary(conversation_id: uuid.UUID, request: Request,
                             user: AuthenticatedUser = Depends(get_current_user)) -> ConversationOut:
    svc = _service(request)
    _require_turns(svc)
    try:
        return ConversationOut.of(await svc.regenerate_summary(user, conversation_id))
    except ConversationNotFound:
        raise HTTPException(status.HTTP_404_NOT_FOUND, detail="Conversation not found") from None
    except NothingToSummarize:
        raise HTTPException(status.HTTP_409_CONFLICT, detail="This conversation is too short to summarise.") from None
    except StoreNotConfigured:
        raise HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail="The assistant isn't available right now.") from None
    except LLMError as exc:
        raise _llm_error(exc) from None


# ============================================================================ proposals (confirmation-only paths)
#
# These are the ONLY way a proposal becomes food logs. They are not tools: the
# model can't call them, and chat messages ("yes", "confirm") don't reach them.
# The app calls them after the user taps Confirm/Cancel on a specific proposal.

_PROPOSAL_STATE = {
    "confirmed": (status.HTTP_409_CONFLICT, "This proposal was already logged."),
    "confirming": (status.HTTP_409_CONFLICT, "This proposal is being logged."),
    "rejected": (status.HTTP_409_CONFLICT, "This proposal was cancelled."),
    "expired": (status.HTTP_410_GONE, "This proposal has expired. Ask the assistant again."),
}


def _proposal_error(exc: Exception) -> HTTPException:
    if isinstance(exc, ProposalNotFound):
        return HTTPException(status.HTTP_404_NOT_FOUND, detail="Proposal not found")
    if isinstance(exc, ProposalStateError):
        code, detail = _PROPOSAL_STATE.get(exc.status, (status.HTTP_409_CONFLICT, "This proposal can't be changed."))
        return HTTPException(code, detail=detail)
    if isinstance(exc, ProposalInvalid):
        return HTTPException(status.HTTP_422_UNPROCESSABLE_ENTITY, detail=" ".join(exc.problems))
    if isinstance(exc, ProposalSaveFailed):
        return HTTPException(status.HTTP_502_BAD_GATEWAY, detail="Couldn't save your food log. Nothing was saved; try again.")
    if isinstance(exc, StoreNotConfigured):
        return HTTPException(status.HTTP_503_SERVICE_UNAVAILABLE, detail="The assistant isn't available right now.")
    raise exc


@router.get("/v1/assistant/proposals/{proposal_id}", response_model=FoodLogProposal, summary="A food-log proposal")
async def get_proposal(proposal_id: uuid.UUID, request: Request,
                       user: AuthenticatedUser = Depends(get_current_user)) -> FoodLogProposal:
    try:
        return await _service(request).proposals.get(user, proposal_id)
    except (ProposalNotFound, StoreNotConfigured) as exc:
        raise _proposal_error(exc) from None


@router.post("/v1/assistant/proposals/{proposal_id}/confirm", response_model=ConfirmResult,
             summary="Log a proposal's foods (explicit user confirmation from the app)",
             responses={404: {"description": "Not found (or not yours)"}, 409: {"description": "Already logged, being logged or cancelled"},
                        410: {"description": "Expired"}, 422: {"description": "No longer valid; nothing saved"},
                        502: {"description": "Save failed; nothing saved; retry allowed"}})
async def confirm_proposal(proposal_id: uuid.UUID, body: ConfirmRequest, request: Request,
                           user: AuthenticatedUser = Depends(get_current_user)) -> ConfirmResult:
    try:
        return await _service(request).proposals.confirm(user, proposal_id, body)
    except (ProposalNotFound, ProposalStateError, ProposalInvalid, ProposalSaveFailed, StoreNotConfigured) as exc:
        raise _proposal_error(exc) from None


@router.post("/v1/assistant/proposals/{proposal_id}/reject", response_model=FoodLogProposal,
             summary="Cancel a proposal")
async def reject_proposal(proposal_id: uuid.UUID, request: Request,
                          user: AuthenticatedUser = Depends(get_current_user)) -> FoodLogProposal:
    try:
        return await _service(request).proposals.reject(user, proposal_id)
    except (ProposalNotFound, ProposalStateError, StoreNotConfigured) as exc:
        raise _proposal_error(exc) from None


